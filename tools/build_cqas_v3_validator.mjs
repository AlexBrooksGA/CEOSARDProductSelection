import fs from 'node:fs';
import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import { build } from 'esbuild';
import standalone from 'ajv/dist/standalone/index.js';
const schema = JSON.parse(fs.readFileSync('src/lib/domain/schemas/cqas-report-v3.json', 'utf8'));
const ajv = new Ajv({allErrors: true, strict: false, code: {source: true, esm: true}});
addFormats(ajv);
const bundle = await build({stdin: {contents: standalone(ajv, ajv.compile(schema)), resolveDir: process.cwd()}, bundle: true, write: false, format: 'esm', platform: 'neutral', mainFields: ['module', 'main'], minify: true});
const output = '// Generated by tools/build_cqas_v3_validator.mjs; do not edit.\n' + bundle.outputFiles[0].text;
const path = 'src/lib/domain/generated/cqas-v3-validator.js';
if (process.argv.includes('--check')) {
 if (fs.readFileSync(path, 'utf8') !== output) throw Error('Stale v3 validator');
} else fs.writeFileSync(path, output);
